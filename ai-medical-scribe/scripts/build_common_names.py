"""Build app/data/common_word_names.txt: gazetteer names that are also ordinary
lowercase English words ("lot", "else", "job", "day", "nelson", "mark").

Source: the SCOWL-based hunspell en_US dictionary (LibreOffice/dictionaries,
BSD-style licence, (c) Kevin Atkinson et al.). Hunspell lists proper nouns
capitalised ("Lot") and common words lowercase ("lot"), so a lowercase entry
means "this is an everyday word". The output file is committed; re-run only if
the gazetteer changes.

    python scripts/build_common_names.py
"""
from __future__ import annotations

import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
DIC_URL = "https://raw.githubusercontent.com/LibreOffice/dictionaries/master/en/en_US.dic"
OUT = ROOT / "app" / "data" / "common_word_names.txt"


def main() -> None:
    from app.redact import name_lexicons

    raw = urllib.request.urlopen(DIC_URL, timeout=60).read().decode("utf-8", "replace")
    words = {ln.split("/")[0] for ln in raw.splitlines()[1:] if ln and ln[0].islower()}
    first, last = name_lexicons()
    common = sorted((first | last) & words)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "# Gazetteer names that are also lowercase words in the SCOWL/hunspell en_US\n"
        "# dictionary (BSD-style licence). Generated by scripts/build_common_names.py.\n"
        "# These are redacted only with name context (greeting, title, 'my name is',\n"
        "# adjacent first/last name, age pattern).\n" + "\n".join(common) + "\n"
    )
    print(f"{len(common)} words -> {OUT}")


if __name__ == "__main__":
    main()
